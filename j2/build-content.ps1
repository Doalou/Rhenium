# Sorties des hooks gclient « lastchange » (gpu/ : révision de la balise ; Skia : celle du DEPS).
$src = "$PSScriptRoot\..\chromium\src"
function Write-LastChange([string] $path, [string] $macro, [string] $rev) {
  $file = Join-Path $src $path
  if (Test-Path $file) { return }
  $guard = ($path -replace '[/\\.]', '_').ToUpper() + '_'
  $text = "/* Generated by lastchange.py, do not edit.*/`n`n#ifndef $guard`n#define $guard`n`n" +
    "#define $macro `"$rev`"`n`n#endif  // $guard`n"
  [IO.File]::WriteAllText($file, $text)
}
$tagRev = ((Get-Content "$src\build\util\LASTCHANGE" -TotalCount 1) -replace '^LASTCHANGE=', '') -replace '-.*$', ''
$skiaRev = (Select-String -Path "$src\..\DEPS-116.0.5845.228" -Pattern "'skia_revision': '([0-9a-f]+)'").Matches[0].Groups[1].Value
Write-LastChange 'gpu/config/gpu_lists_version.h' 'GPU_LISTS_VERSION' $tagRev
Write-LastChange 'skia/ext/skia_commit_hash.h' 'SKIA_COMMIT_HASH' $skiaRev

# Sources de l'app (cible rhenium_shell de gn\BUILD.gn).
New-Item -ItemType Directory -Force "$src\rhenium" | Out-Null
Copy-Item "$PSScriptRoot\app\*.cc", "$PSScriptRoot\app\*.h", "$PSScriptRoot\..\j1\app\w10m_imports.cc" "$src\rhenium\" -Force

